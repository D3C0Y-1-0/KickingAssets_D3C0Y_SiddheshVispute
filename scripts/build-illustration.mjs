// Original figure: a three-bay infrastructure control station on one engineered base.
// Sector selection highlights a cabinet; there are no readings or implied telemetry.
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import * as k from '../.agents/skills/anatomy/kit/iso-kit.mjs'
import * as A from '../.agents/skills/anatomy/kit/audit.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const plate = { x: -149, y: -80, w: 298, d: 193, r: 5 }
const P = k.fitProjection([...k.boxCorners(plate, -18, 0), ...k.boxCorners({ x: -117, y: -47, w: 234, d: 42, r: 1 }, 0, 116)], 580, 390, { pad: 22, azimuth: 48, elevation: 29 })
const R = A.recorder(P)
const at = p => k.iso(p, P)
const line = (d, tone = 'lo') => k.lineSvg(d, { tone })
function box(name, plan, z, h, { tone = 'mid', sector = '', inner = '' } = {}) {
  const shape = R.solid(A.slab(plan, z, h, { name, ground: name.startsWith('foot-') }))
  const svg = `<g${sector ? ` data-sector="${sector}"` : ''}>${k.solidSvg(k.slabOf(plan, z, h, P, 4, .6), { tone, inner })}</g>`
  R.put({ name, at: [plan.x + plan.w / 2, plan.y + plan.d / 2, z + h / 2], shapes: [shape], svg })
}
for (const [i, [x, y]] of k.corners(plate, 17).entries()) box(`foot-${i}`, { x: x - 7, y: y - 7, w: 14, d: 14, r: 2 }, -18, 6, { tone: 'lo' })
box('base', plate, -12, 12, { tone: 'lo', inner: line(k.planOutline(k.insetPlan(plate, 5), 0, P), 'faint') + k.dotsSvg(k.pointsAt(k.corners(plate, 10).map(([x,y]) => [x,y,0]), P), { size: .8 }) })
for (const [i, sector] of ['power', 'water', 'healthcare'].entries()) {
  const x = -117 + i * 81
  const y = -47
  const w = 64, d = 42
  box(`${sector}.plinth`, { x: x - 2, y: y - 2, w: w + 4, d: d + 4, r: 2 }, 0, 7, { tone: 'lo', sector })
  box(`${sector}.back`, { x, y, w, d: 2, r: .3 }, 7, 103, { sector })
  box(`${sector}.side-left`, { x, y: y + 2, w: 2, d: d - 2, r: .3 }, 7, 103, { sector })
  box(`${sector}.side-right`, { x: x + w - 2, y: y + 2, w: 2, d: d - 2, r: .3 }, 7, 103, { sector })
  box(`${sector}.cap`, { x, y, w, d, r: 1 }, 110, 4, { sector, tone: 'hi' })
  for (let row = 0; row < 6; row++) {
    const z = 10 + row * 16
    const frontY = y + d
    const face = points => k.pathOf(points.map(([u,v]) => at([u,frontY,v])), true)
    const vents = Array.from({ length: 7 }, (_, n) => line(face([[x+9+n*5,z+5],[x+11+n*5,z+5],[x+11+n*5,z+10],[x+9+n*5,z+10]]), 'faint')).join('')
    const screws = k.dotsSvg(k.pointsAt([[x+5,frontY,z+3],[x+w-5,frontY,z+3],[x+5,frontY,z+12],[x+w-5,frontY,z+12]], P), { size: .55 })
    box(`${sector}.module-${row}`, { x: x + 2, y: y + 2, w: w - 4, d: d - 2, r: .7 }, z, 14, { sector, tone: 'mid', inner: vents + screws })
  }
  box(`${sector}.feed`, { x: x + 28, y: -3, w: 6, d: 16, r: .4 }, 0, 4, { sector, tone: 'lo' })
}
box('backplane', { x: -89, y: 13, w: 169, d: 6, r: 1 }, 0, 4, { tone: 'lo' })
box('console-feed', { x: -7, y: 19, w: 6, d: 21, r: .4 }, 0, 4, { tone: 'lo' })
for (const [i, x] of [-52, 50].entries()) box(`console.leg-${i}`, { x, y: 42, w: 5, d: 38, r: .7 }, 0, 27, { tone: 'lo' })
box('console.desk', { x: -62, y: 39, w: 126, d: 48, r: 3 }, 27, 5, { tone: 'hi' })
box('monitor.foot', { x: -17, y: 44, w: 36, d: 17, r: 1 }, 32, 3, { tone: 'mid' })
box('monitor.stand', { x: -4, y: 47, w: 10, d: 7, r: .6 }, 35, 10)
box('monitor.housing', { x: -49, y: 46, w: 102, d: 9, r: 2 }, 45, 49, { tone: 'hi' })
box('monitor.screen', { x: -43, y: 55, w: 90, d: .3, r: 1 }, 51, 36, { tone: 'hi', inner: line(k.pathOf([[-35,55.3,57],[-35,55.3,79],[39,55.3,79],[39,55.3,57]].map(at), true), 'faint') })
for (let i = 0; i < 3; i++) {
  box(`console.key-row-${i}`, { x: -35, y: 66 + i * 5, w: 66, d: 3.5, r: .4 }, 32, 2, { tone: 'lo' })
}
box('console.trackpad', { x: 41, y: 67, w: 13, d: 13, r: 1 }, 32, 1, { tone: 'lo' })
for (const [i, x] of [-135, 132].entries()) box(`floor-anchor-${i}`, { x, y: 90, w: 7, d: 7, r: .5 }, 0, 1, { tone: 'lo' })
A.settle(R, P)
R.items.sort((a, b) => a.key - b.key)
A.auditOrExit(R, P)
if (process.exitCode) process.exit(process.exitCode)
const body = `<path class="iso-halo" d="${k.haloOf(plate,-18,10,P)}"/>${R.items.map(item => item.svg).join('')}`
const dir = resolve(root, 'frontend/src/components/illustration')
mkdirSync(dir, { recursive: true })
writeFileSync(resolve(dir, 'station-art.ts'), `// Generated by scripts/build-illustration.mjs. Original GridSentinel geometry.\nexport const stationArt = ${JSON.stringify(body)}\nexport const stationPartCount = ${R.items.length}\n`)
console.log(`Built control station: ${R.items.length} supported solids, static SVG, no runtime kit dependency.`)
